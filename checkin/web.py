def _session_token(password: str) -> str:
    return hashlib.sha256(f"auto-checkin::{password}".encode()).hexdigest()


def _sync_tool_token(password: str) -> str:
    return hmac.new(password.encode(), SYNC_TOOL_TOKEN_MSG.encode(), hashlib.sha256).hexdigest()


